"""
Report Generation Service for KissanConnect.
Produces professional PDF and Excel advisory reports for farmers and stakeholders.
"""

import io
import re
import logging
from datetime import datetime
from typing import Dict, Any

from django.http import HttpResponse, JsonResponse
import xlsxwriter
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors

logger = logging.getLogger(__name__)


def generate_pdf_report(report_data: Dict[str, Any]) -> HttpResponse:
    """Generate high-resolution printable PDF crop advisory report."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()
    story = []

    # Title
    title_style = ParagraphStyle(
        'CustomTitle',
        parent=styles['Heading1'],
        fontSize=22,
        spaceAfter=15,
        textColor=colors.HexColor('#2E7D32'),
        alignment=1
    )
    story.append(Paragraph("🌾 Kissan Connect — Comprehensive Agronomic Report", title_style))
    story.append(Spacer(1, 10))

    # Farm Information
    story.append(Paragraph("📋 Farm Profile & Parameters", styles['Heading2']))
    farm_info = [
        ['Location:', report_data.get('location', 'N/A')],
        ['State:', report_data.get('state', 'N/A')],
        ['Country:', report_data.get('country', 'N/A')],
        ['Season:', str(report_data.get('season', 'N/A')).title()],
        ['Farm Size:', f"{report_data.get('farm_size', 'N/A')} acres"],
        ['Budget Range:', str(report_data.get('budget', 'N/A')).title()],
        ['Irrigation Type:', str(report_data.get('irrigation', 'N/A')).title()],
        ['Report Date:', datetime.now().strftime('%B %d, %Y (%I:%M %p)')]
    ]

    farm_table = Table(farm_info, colWidths=[150, 350])
    farm_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAF8')),
        ('TEXTCOLOR', (0, 0), (-1, -1), colors.black),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#E8F5E9')),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#C8E6C9'))
    ]))
    story.append(farm_table)
    story.append(Spacer(1, 15))

    # Weather Conditions
    weather_data = report_data.get('weather_data', {})
    if weather_data:
        story.append(Paragraph("🌤️ Microclimate & Weather Intelligence", styles['Heading2']))
        weather_info = [
            ['Ambient Temperature:', f"{weather_data.get('temperature', 'N/A')}°C (Feels like {weather_data.get('feels_like', 'N/A')}°C)"],
            ['Relative Humidity:', f"{weather_data.get('humidity', 'N/A')}%"],
            ['Sky Condition:', str(weather_data.get('description', 'N/A')).title()],
            ['Wind Speed:', f"{weather_data.get('wind_speed', 'N/A')} km/h"]
        ]
        weather_table = Table(weather_info, colWidths=[150, 350])
        weather_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F0F7FF')),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.black),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#E1F0FF')),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#BADCFF'))
        ]))
        story.append(weather_table)
        story.append(Spacer(1, 15))

    # Recommendations
    story.append(Paragraph("🌱 AI Crop & Management Recommendations", styles['Heading2']))
    raw_rec = report_data.get('recommendations', 'No recommendations recorded.')
    clean_rec = re.sub(r'<.*?>', '', str(raw_rec))
    story.append(Paragraph(clean_rec.replace('\n', '<br/>'), styles['Normal']))
    story.append(Spacer(1, 20))

    # Footer
    footer_style = ParagraphStyle(
        'Footer', parent=styles['Normal'], fontSize=8, textColor=colors.grey, alignment=1
    )
    story.append(Paragraph(f"Generated by Kissan Connect AI Platform • Verified Agricultural System • {datetime.now().strftime('%Y-%m-%d')}", footer_style))

    doc.build(story)
    buffer.seek(0)

    response = HttpResponse(buffer.getvalue(), content_type='application/pdf')
    filename = f"kissan_advisory_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    response['Content-Disposition'] = f'attachment; filename="{filename}"'
    return response


def generate_excel_report(report_data: Dict[str, Any]) -> HttpResponse:
    """Generate Excel workbook with structured agronomic parameters."""
    output = io.BytesIO()
    workbook = xlsxwriter.Workbook(output, {'in_memory': True})
    worksheet = workbook.add_worksheet('Crop Analysis Report')

    title_fmt = workbook.add_format({
        'bold': True, 'font_size': 14, 'align': 'center', 'valign': 'vcenter',
        'bg_color': '#2E7D32', 'font_color': 'white'
    })
    header_fmt = workbook.add_format({
        'bold': True, 'font_size': 11, 'bg_color': '#E8F5E9', 'border': 1
    })
    data_fmt = workbook.add_format({'border': 1, 'text_wrap': True})

    worksheet.merge_range('A1:C1', '🌾 Kissan Connect — Advisory Report', title_fmt)
    worksheet.set_row(0, 25)
    worksheet.set_column('A:A', 22)
    worksheet.set_column('B:B', 35)

    farm_data = [
        ['Location', report_data.get('location', 'N/A')],
        ['State', report_data.get('state', 'N/A')],
        ['Season', str(report_data.get('season', 'N/A')).title()],
        ['Farm Size', f"{report_data.get('farm_size', 'N/A')} acres"],
        ['Budget', str(report_data.get('budget', 'N/A')).title()],
        ['Irrigation', str(report_data.get('irrigation', 'N/A')).title()],
        ['Generated Date', datetime.now().strftime('%Y-%m-%d %H:%M')],
    ]

    worksheet.write(2, 0, 'Parameter', header_fmt)
    worksheet.write(2, 1, 'Value', header_fmt)

    for idx, (param, val) in enumerate(farm_data, start=3):
        worksheet.write(idx, 0, param, data_fmt)
        worksheet.write(idx, 1, val, data_fmt)

    workbook.close()
    output.seek(0)

    response = HttpResponse(
        output.getvalue(),
        content_type='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    )
    filename = f"kissan_analysis_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
    response['Content-Disposition'] = f'attachment; filename="{filename}"'
    return response
